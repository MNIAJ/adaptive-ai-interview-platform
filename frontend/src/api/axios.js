import axios from 'axios'

// Single shared axios instance. Every request automatically gets the JWT
// attached (if we have one) — no need to remember this in every page.
const api = axios.create({
  baseURL: 'http://localhost:8080/api',
})

api.interceptors.request.use((config) => {
  const token = localStorage.getItem('token')
  if (token) config.headers.Authorization = `Bearer ${token}`
  return config
})

// If the backend ever says "your token is invalid/expired", kick back to login
// instead of silently failing on every subsequent request.
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response?.status === 401) {
      localStorage.removeItem('token')
      window.location.href = '/login'
    }
    return Promise.reject(error)
  }
)

export default api
